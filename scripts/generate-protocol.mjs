import { readFileSync, writeFileSync } from 'node:fs';

// Generate the internal camelCase models from the pinned, official JSON schemas.
// Nullable wire fields become optional; ticks always use bigint internally.
const source = JSON.parse(readFileSync(new URL('../schemas/SOURCE.json', import.meta.url), 'utf8'));
const repository = new URL(source.repository);
const base = `https://raw.githubusercontent.com${repository.pathname}/${source.revision}/`;
const schemas = await Promise.all(source.files.map(async file => {
  const url = new URL(file, base);
  const response = await fetch(url, { signal: AbortSignal.timeout(30000) });
  if (!response.ok) throw new Error(`Failed to fetch ${url}: HTTP ${response.status}`);
  const schema = await response.json();
  if (!schema.$defs) throw new Error(`Missing $defs in ${url}`);
  return schema;
}));
const defs = Object.assign({}, ...schemas.map(schema => schema.$defs));
const camel = name => name.replace(/_([a-z])/g, (_, c) => c.toUpperCase());
const nullable = schema => schema.const === null || schema.type === 'null' || schema.type?.includes?.('null') || schema.anyOf?.some(nullable);
function type(schema) {
  if (schema.$ref) return schema.$ref.split('/').at(-1);
  if ('const' in schema) return schema.const === null ? 'undefined' : JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map(v => JSON.stringify(v)).join(' | ');
  if (schema.anyOf || schema.oneOf) return (schema.anyOf ?? schema.oneOf).map(type).join(' | ');
  if (Array.isArray(schema.type)) return schema.type.map(t => type({ ...schema, type: t })).join(' | ');
  if (schema.type === 'null') return 'undefined';
  if (schema.type === 'integer') return Number.isSafeInteger(schema.maximum) ? 'number' : 'bigint';
  if (schema.type === 'array') return `Array<${type(schema.items)}>`;
  if (schema.type === 'object') {
    if (!schema.properties) return `Record<string, ${type(schema.additionalProperties)}>`;
    return `{ ${Object.entries(schema.properties).map(([name, s]) => `${camel(name)}${nullable(s) || !schema.required?.includes(name) ? '?' : ''}: ${type(s)};`).join(' ')} }`;
  }
  return schema.type;
}
const output = '// Generated by scripts/generate-protocol.mjs. Do not edit.\n'
  + `// Source: ${source.repository}/tree/${source.revision}/schemas/v${source.protocol}\n`
  + Object.entries(defs).map(([name, schema]) => `export type ${name} = ${type(schema)};`).join('\n')
  + '\n' + ['TimerPhase', 'TimingMethod'].map(name => `export const ${name} = ${JSON.stringify(Object.fromEntries(defs[name].enum.map(v => [v.toUpperCase(), v])))} as const;`).join('\n')
  + '\nexport const BridgeEventType = ' + JSON.stringify(Object.fromEntries(['timer_started', 'timer_split', 'timer_skipped', 'timer_undo', 'timer_phase_changed', 'timer_reset', 'run_changed', 'context_changed'].map(v => [`EVENT_${v.toUpperCase()}`, v]))) + ' as const;\n'
  + 'export const definitions = ' + JSON.stringify(defs) + ';\n';
writeFileSync(new URL('../src/generated/protocol.ts', import.meta.url), output);
